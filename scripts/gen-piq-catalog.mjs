/**
 * Emit the PIQ question catalogue as SQL.
 *
 * `piq-config.ts` is the single source of truth for what a PIQ asks, but it
 * lives in TypeScript where Postgres can't see it — so the database stores
 * answers keyed by field id (`shelf_life`) with no idea what they mean. This
 * script mirrors the config into the `PIQQuestion` table that the
 * `v_piq_answer` view joins against for human-readable labels.
 *
 * Run it whenever the config changes, and paste the output into a new
 * migration in afrizonemart-api:
 *
 *   node scripts/gen-piq-catalog.mjs > /tmp/piq-catalog.sql
 *
 * The generated statement is an idempotent upsert, so re-running it is safe.
 * Questions deleted from the config are left in the table on purpose: old
 * PIQs still hold answers keyed by them, and the view should keep labelling
 * those rows rather than degrading them to a bare field id.
 */
import { PIQ_GENERAL_CONFIG } from '../src/lib/supplier/piq-config.ts';

/** Postgres string literal — double up single quotes. */
const lit = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`);

const rows = [];
let position = 0;
for (const section of PIQ_GENERAL_CONFIG.sections) {
  for (const q of section.questions) {
    position += 1;
    rows.push(
      `  (${lit(q.id)}, ${lit(section.id)}, ${lit(section.title)}, ${lit(q.label)}, ` +
        `${lit(q.type)}, ${q.required ? 'true' : 'false'}, ${position})`,
    );
  }
}

process.stdout.write(
  `-- ${rows.length} questions from PIQ_GENERAL_CONFIG v${PIQ_GENERAL_CONFIG.version}.\n` +
    `-- Generated by afrizonemart-v2/scripts/gen-piq-catalog.mjs — do not hand-edit.\n` +
    `INSERT INTO "PIQQuestion" ("id", "section", "sectionTitle", "label", "type", "required", "position") VALUES\n` +
    rows.join(',\n') +
    `\nON CONFLICT ("id") DO UPDATE SET\n` +
    `  "section"      = EXCLUDED."section",\n` +
    `  "sectionTitle" = EXCLUDED."sectionTitle",\n` +
    `  "label"        = EXCLUDED."label",\n` +
    `  "type"         = EXCLUDED."type",\n` +
    `  "required"     = EXCLUDED."required",\n` +
    `  "position"     = EXCLUDED."position";\n`,
);
